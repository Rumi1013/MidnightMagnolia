#!/usr/bin/env node
/**
 * Emit CSV + SQL seed from data/flagship/institute-resources.json.
 * Does not connect to Supabase. Run: node scripts/flagship-institute-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const categories = JSON.parse(readFileSync(join(root, 'data/flagship/institute-categories.json'), 'utf8'));
const pack = JSON.parse(readFileSync(join(root, 'data/flagship/institute-resources.json'), 'utf8'));

function sqlStr(value) {
  if (value == null || value === '') return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function csvCell(value) {
  if (value == null) return '';
  const text = String(value);
  if (/[",\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
  return text;
}

const errors = [];
if (pack.resources.length !== 20) {
  errors.push(`expected 20 resources, found ${pack.resources.length}`);
}
const seen = new Set();
for (const row of pack.resources) {
  if (seen.has(row.seed_id)) errors.push(`duplicate ${row.seed_id}`);
  seen.add(row.seed_id);
  if (!row.website || !row.website.startsWith('https://')) {
    errors.push(`${row.seed_id} missing https website`);
  }
  if (!row.categories?.length) errors.push(`${row.seed_id} has no category`);
  if (!row.description) errors.push(`${row.seed_id} missing description`);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const csvHeader = [
  'resource_id', 'organization', 'program', 'description', 'website', 'phone',
  'city', 'county', 'state', 'virtual_available', 'status', 'categories',
  'last_verified', 'next_review', 'provenance_url',
];
const csvRows = [csvHeader.join(',')];
const sql = [
  '-- Generated by scripts/flagship-institute-seed.mjs. Do not edit by hand.',
  '-- Run after lib/flagship/institute-schema.sql.',
  '',
];

for (const cat of categories) {
  sql.push(
    `insert into institute_category (id, name, description) values (${sqlStr(cat.id)}, ${sqlStr(cat.name)}, ${sqlStr(cat.description)})`,
    '  on conflict (id) do update set name = excluded.name, description = excluded.description;',
  );
}
sql.push('');

for (const row of pack.resources) {
  const loc = row.location || {};
  csvRows.push([
    row.seed_id, row.organization, row.program, row.description, row.website, row.phone,
    loc.city, loc.county, loc.state, loc.virtual_available, pack.status,
    row.categories.join('|'), pack.reviewed_on, pack.next_review_on, row.website,
  ].map(csvCell).join(','));

  sql.push(
    `insert into institute_resource (id, organization, program, description, website, phone, email, status, classification, last_verified_on, next_review_on, provenance_url)`,
    `values (${sqlStr(row.seed_id)}, ${sqlStr(row.organization)}, ${sqlStr(row.program)}, ${sqlStr(row.description)}, ${sqlStr(row.website)}, ${sqlStr(row.phone)}, null, ${sqlStr(pack.status)}, ${sqlStr(pack.classification)}, ${sqlStr(pack.reviewed_on)}, ${sqlStr(pack.next_review_on)}, ${sqlStr(row.website)})`,
    '  on conflict (id) do update set organization = excluded.organization, program = excluded.program, description = excluded.description, website = excluded.website, phone = excluded.phone, status = excluded.status, last_verified_on = excluded.last_verified_on, next_review_on = excluded.next_review_on, provenance_url = excluded.provenance_url;',
  );

  row.categories.forEach((catId, index) => {
    sql.push(
      `insert into institute_resource_category (resource_id, category_id, is_primary) values (${sqlStr(row.seed_id)}, ${sqlStr(catId)}, ${index === 0})`,
      '  on conflict (resource_id, category_id) do update set is_primary = excluded.is_primary;',
    );
  });

  const elig = row.eligibility || {};
  const access = row.accessibility || {};
  sql.push(
    `insert into institute_location (id, resource_id, city, county, state, virtual_available) values (${sqlStr(`${row.seed_id}-loc`)}, ${sqlStr(row.seed_id)}, ${sqlStr(loc.city)}, ${sqlStr(loc.county)}, ${sqlStr(loc.state)}, ${loc.virtual_available === true})`,
    '  on conflict (id) do update set city = excluded.city, county = excluded.county, state = excluded.state, virtual_available = excluded.virtual_available;',
    `insert into institute_eligibility (id, resource_id, population, age_range, requirements, cost, insurance_sliding_scale) values (${sqlStr(`${row.seed_id}-elig`)}, ${sqlStr(row.seed_id)}, ${sqlStr(elig.population)}, ${sqlStr(elig.age_range)}, ${sqlStr(elig.requirements)}, ${sqlStr(elig.cost)}, ${sqlStr(elig.insurance_sliding_scale)})`,
    '  on conflict (id) do update set population = excluded.population, age_range = excluded.age_range, requirements = excluded.requirements, cost = excluded.cost, insurance_sliding_scale = excluded.insurance_sliding_scale;',
    `insert into institute_accessibility (id, resource_id, mobility, language, virtual, transportation, accommodations) values (${sqlStr(`${row.seed_id}-acc`)}, ${sqlStr(row.seed_id)}, ${sqlStr(access.mobility)}, ${sqlStr(access.language)}, ${sqlStr(access.virtual)}, ${sqlStr(access.transportation)}, ${sqlStr(access.accommodations)})`,
    '  on conflict (id) do update set mobility = excluded.mobility, language = excluded.language, virtual = excluded.virtual, transportation = excluded.transportation, accommodations = excluded.accommodations;',
    `insert into institute_verification (id, resource_id, verified_on, method, reviewer_role, result, next_review, notes) values (${sqlStr(`${row.seed_id}-ver`)}, ${sqlStr(row.seed_id)}, ${sqlStr(pack.reviewed_on)}, ${sqlStr(pack.method)}, ${sqlStr(pack.reviewer_role)}, ${sqlStr(pack.status)}, ${sqlStr(pack.next_review_on)}, ${sqlStr(pack.notes)})`,
    '  on conflict (id) do update set verified_on = excluded.verified_on, method = excluded.method, result = excluded.result, next_review = excluded.next_review, notes = excluded.notes;',
    '',
  );
}

writeFileSync(join(root, 'data/flagship/institute-resources.csv'), `${csvRows.join('\n')}\n`);
while (sql.at(-1) === '') sql.pop();
writeFileSync(join(root, 'lib/flagship/institute-seed.sql'), `${sql.join('\n')}\n`);
console.log(`Wrote ${pack.resources.length} Institute seed rows.`);
